  await period('todo-list', 'last'); assert.deepEqual(await titles('todo-list'), ['지난주 마지막']);
  assert.match(await section('todo-list').locator('.completion-count').innerText(), /2026-10-19 ~ 2026-10-25.*1개/);
  await period('todo-list', 'previous');
