  // 한국 월요일로 넘어가면 열린 페이지의 기본 이번 주도 다음 범위로 갱신됩니다.
  await page.clock.fastForward(new Date('2026-11-01T15:00:01Z').getTime() - new Date('2026-10-28T03:00:01Z').getTime());
  assert.match(await section('todo-list').locator('.completion-count').innerText(), /2026-11-02 ~ 2026-11-08.*0개/);
  assert.match(await section('todo-list').innerText(), /선택한 주에 완료된 항목이 없어요/);
