  assert.match(await section('todo-list').locator('.completion-count').innerText(), /2020-01-06 ~ 2020-01-12/);
  await period('todo-list', 'unknown'); assert.deepEqual(await titles('todo-list'), ['완료일 미상 기록']);
  await page.locator('#open-mypage').click();
  assert.equal(await section('my-todo-list').getAttribute('open'), null);
